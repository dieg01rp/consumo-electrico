# Carga y descarga automática del dataset desde UCI (evita el límite de GitHub)
@st.cache_data
def descargar_y_procesar_datos():
    url = "https://archive.ics.uci.edu/static/public/235/individual+household+electric+power+consumption.zip"
    zip_path = "household_power_consumption.zip"
    txt_path = "household_power_consumption.txt"

    if not os.path.exists(txt_path):
        with st.spinner("Descargando el dataset desde el repositorio oficial de UCI (esto puede tomar un momento)..."):
            urllib.request.urlretrieve(url, zip_path)
            with zipfile.ZipFile(zip_path, 'r') as zip_ref:
                # Verificación de seguridad para evitar Zip Slip (CWE-22)
                for member in zip_ref.namelist():
                    filename = os.path.basename(member)
                    if not filename:
                        continue
                    source = zip_ref.open(member)
                    target = open(os.path.join(os.getcwd(), filename), "wb")
                    with source, target:
                        target.write(source.read())
            if os.path.exists(zip_path):
                os.remove(zip_path)

    df_raw = pd.read_csv(txt_path, sep=';', na_values=['?'], low_memory=False)
    df_raw['datetime'] = pd.to_datetime(df_raw['Date'] + ' ' + df_raw['Time'], format='%d/%m/%Y %H:%M:%S', errors='coerce')
    df_raw.dropna(subset=['datetime'], inplace=True)
    df_raw.set_index('datetime', inplace=True)
    df_raw['Global_active_power'] = pd.to_numeric(df_raw['Global_active_power'], errors='coerce')

    df_raw['energia_kwh'] = df_raw['Global_active_power'] / 60
    df_raw['hora'] = df_raw.index.hour
    df_raw['fecha'] = df_raw.index.date
    df_raw['dia_semana'] = df_raw.index.dayofweek

    mask_diurno = (df_raw['hora'] >= 8) & (df_raw['hora'] < 18)
    mask_nocturno = (df_raw['hora'] >= 22) | (df_raw['hora'] < 8)
    mask_pico = (df_raw['hora'] >= 18) & (df_raw['hora'] < 22)

    daily = df_raw.groupby('fecha').agg(
        consumo_total_kwh=('energia_kwh', 'sum'),
        potencia_max=('Global_active_power', 'max'),
        variabilidad=('Global_active_power', 'std'),
        dia_semana=('dia_semana', 'first')
    )

    daily['consumo_diurno'] = df_raw[mask_diurno].groupby('fecha')['energia_kwh'].sum()
    daily['consumo_nocturno'] = df_raw[mask_nocturno].groupby('fecha')['energia_kwh'].sum()
    daily['consumo_pico'] = df_raw[mask_pico].groupby('fecha')['energia_kwh'].sum()
    daily['consumo_finde'] = np.where(daily['dia_semana'] >= 5, daily['consumo_total_kwh'], 0)
    daily['factor_carga'] = (daily['consumo_total_kwh'] / 24) / daily['potencia_max']

    features = ['consumo_diurno', 'consumo_nocturno', 'consumo_pico', 'consumo_finde', 'variabilidad', 'factor_carga']
    X = daily[features].dropna()
    return X, features

try:
    X, features = descargar_y_procesar_datos()
    st.sidebar.success(f"Datos listos. Registros diarios: {X.shape[0]}")

    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X)
    X_scaled_df = pd.DataFrame(X_scaled, columns=features, index=X.index)

    tab1, tab2, tab3, tab4 = st.tabs(["Exploración y Preprocesamiento", "K-Means y DBSCAN", "Análisis PCA", "Evaluación Comparativa"])

    with tab1:
        st.subheader("Análisis Exploratorio de Datos (EDA)")
        col1, col2 = st.columns(2)
        with col1:
            var_sel = st.selectbox("Seleccionar variable para histograma", features)
            fig, ax = plt.subplots(figsize=(8, 4))
            sns.histplot(X[var_sel], bins=30, kde=True, ax=ax, color="#1f4e78")
            ax.set_title(f"Distribución de {var_sel}")
            st.pyplot(fig)
        with col2:
            st.markdown("Matriz de Correlación entre Variables")
            fig, ax = plt.subplots(figsize=(6, 4))
            sns.heatmap(X.corr(), annot=True, cmap="vlag", fmt=".2f", ax=ax, annot_kws={"size": 8})
            st.pyplot(fig)
        st.markdown("Estadísticas Descriptivas")
        st.dataframe(X.describe())

    with tab2:
        st.subheader("Modelos de Agrupamiento: K-Means y DBSCAN")
        col_k1, col_k2 = st.columns(2)
        with col_k1:
            st.markdown("K-Means")
            k_val = st.slider("Número de Clústeres (K)", 2, 10, 3)
            kmeans = KMeans(n_clusters=k_val, init='k-means++', n_init=10, random_state=42)
            labels_km = kmeans.fit_predict(X_scaled)

            sil_km = silhouette_score(X_scaled, labels_km)
            dbi_km = davies_bouldin_score(X_scaled, labels_km)
            chi_km = calinski_harabasz_score(X_scaled, labels_km)

            st.metric("Silhouette K-Means", f"{sil_km:.4f}")
            st.metric("Davies-Bouldin K-Means", f"{dbi_km:.4f}")
            st.metric("Calinski-Harabasz K-Means", f"{chi_km:.4f}")

        with col_k2:
            st.markdown("DBSCAN")
            eps_val = st.slider("Epsilon (eps)", 0.1, 3.0, 0.8, 0.1)
            min_samp = st.slider("Min Samples", 2, 15, 5)

            dbscan = DBSCAN(eps=eps_val, min_samples=min_samp)
            labels_db = dbscan.fit_predict(X_scaled)

            n_clust_db = len(set(labels_db)) - (1 if -1 in labels_db else 0)
            n_noise = list(labels_db).count(-1)
            pct_noise = (n_noise / len(labels_db)) * 100

            st.metric("Clústeres DBSCAN Encontrados", n_clust_db)
            st.metric("Porcentaje de Ruido", f"{pct_noise:.2f}%")

            if n_clust_db >= 2:
                mask_val = labels_db != -1
                sil_db = silhouette_score(X_scaled[mask_val], labels_db[mask_val])
                st.metric("Silhouette (Excluyendo Ruido)", f"{sil_db:.4f}")
            else:
                st.warning("Configuración actual no genera suficientes clústeres válidos.")

        st.markdown("Centroides K-Means (Unidades Originales)")
        centroides_orig = pd.DataFrame(scaler.inverse_transform(kmeans.cluster_centers_), columns=features)
        centroides_orig['Cluster'] = range(k_val)
        st.dataframe(centroides_orig.set_index('Cluster').round(2))

    with tab3:
        st.subheader("Reducción de Dimensionalidad con PCA")
        pca = PCA(random_state=42)
        X_pca = pca.fit_transform(X_scaled)
        var_exp = pca.explained_variance_ratio_
        var_acum = np.cumsum(var_exp)

        fig, ax = plt.subplots(figsize=(8, 4))
        ax.bar(range(1, len(var_exp)+1), var_exp, alpha=0.7, align='center', label='Varianza individual', color='#1f4e78')
        ax.step(range(1, len(var_acum)+1), var_acum, where='mid', label='Varianza acumulada', color='#c55a11')
        ax.axhline(y=0.95, color='r', linestyle='--', label='Umbral 95%')
        ax.set_ylabel('Proporción de Varianza Explicada')
        ax.set_xlabel('Componente Principal')
        ax.legend(loc='best')
        st.pyplot(fig)

        n_comp = np.argmax(var_acum >= 0.90) + 1
        st.info(f"Componentes necesarias para superar el 90% de varianza explicada: {n_comp}")

        loadings = pd.DataFrame(pca.components_.T, columns=[f'PC{i+1}' for i in range(len(features))], index=features)
        st.dataframe(loadings.round(3))

    with tab4:
        st.subheader("Matriz de Evaluación Comparativa")
        X_pca_2d = X_pca[:, :2]

        km_pca = KMeans(n_clusters=k_val, init='k-means++', n_init=10, random_state=42)
        lbl_km_pca = km_pca.fit_predict(X_pca_2d)
        sil_km_pca = silhouette_score(X_pca_2d, lbl_km_pca)
        dbi_km_pca = davies_bouldin_score(X_pca_2d, lbl_km_pca)
        chi_km_pca = calinski_harabasz_score(X_pca_2d, lbl_km_pca)

        db_pca = DBSCAN(eps=0.5, min_samples=5)
        lbl_db_pca = db_pca.fit_predict(X_pca_2d)
        n_c_dbp = len(set(lbl_db_pca)) - (1 if -1 in lbl_db_pca else 0)
        n_r_dbp = list(lbl_db_pca).count(-1)
        pct_r_dbp = (n_r_dbp / len(lbl_db_pca)) * 100

        if n_c_dbp >= 2:
            m_v = lbl_db_pca != -1
            sil_dbp = silhouette_score(X_pca_2d[m_v], lbl_db_pca[m_v])
            dbi_dbp = davies_bouldin_score(X_pca_2d[m_v], lbl_db_pca[m_v])
            chi_dbp = calinski_harabasz_score(X_pca_2d[m_v], lbl_db_pca[m_v])
        else:
            sil_dbp, dbi_dbp, chi_dbp = float('nan'), float('nan'), float('nan')

        tabla_comparativa = pd.DataFrame([
            ["K-Means", k_val, sil_km, dbi_km, chi_km, "0% (Asigna todos)"],
            ["DBSCAN", n_clust_db, sil_db if 'sil_db' in locals() else float('nan'), dbi_db if 'dbi_db' in locals() else float('nan'), chi_db if 'chi_db' in locals() else float('nan'), f"{pct_noise:.2f}%"],
            ["PCA + K-Means", k_val, sil_km_pca, dbi_km_pca, chi_km_pca, "0% (Asigna todos)"],
            ["PCA + DBSCAN", n_c_dbp, sil_dbp, dbi_dbp, chi_dbp, f"{pct_r_dbp:.2f}%"]
        ], columns=["Modelo", "N Clústeres", "Silhouette", "Davies-Bouldin", "Calinski-Harabasz", "Ruido / Cobertura"])

        st.dataframe(tabla_comparativa.round(4))

except Exception as e:
    st.error(f"Error al procesar los datos: {e}")